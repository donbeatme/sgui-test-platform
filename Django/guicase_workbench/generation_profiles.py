def profile_for(options):
    return PROFILES.get(options.get('generation_profile'), PROFILES['detailed'])


def validate_profile(value):
    if not isinstance(value, str) or value not in PROFILES:
        raise ValidationError('生成方式无效，请选择场景演示、业务流程与边界、快速试生成或按功能模块细分。')
    return value
